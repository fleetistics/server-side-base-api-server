-- App structure tables (application_menu, application_menu_item, application_page, role2menu_item).
-- application_menu, application_menu_item, application_page exist in the databases (created by hand); their migration
--   20261117082225_AppStructureMenuAndPageTables has an empty Up.
-- role2menu_item is created by migration 20261117093526_AppStructureRole2MenuItemCreate (CREATE TABLE IF NOT EXISTS);
--   the earlier 20261117092433_AppStructureRole2MenuItemTable has an empty Up (that is what was applied).
--   its LatestUpdate trigger is added by 20261117095604_AppStructureRole2MenuItemLatestUpdateTrigger.
-- The triggers below need the function update_latestupdate_column(), which is created by an early migration and must exist.
-- Run this script on a FRESH database only if the migrations are not applied, or to create the tables by hand.
-- Derived from the scaffolded CreateTable calls. NOTE: the real column types/constraints of the existing hand-made
-- tables were NOT verified against this script. No foreign keys or indexes are modelled.
-- LatestUpdate is the optimistic-concurrency column (DEFAULT now()), maintained on UPDATE by trg_<table>_latest_update.

CREATE TABLE IF NOT EXISTS application_menu (
	"Id" integer GENERATED BY DEFAULT AS IDENTITY,
	"MenuKind" smallint NOT NULL,
	"Name" text NULL,
	"OwnerCompanyId" integer NULL,
	"LatestUpdate" timestamp with time zone NOT NULL DEFAULT now(),
	CONSTRAINT "PK_application_menu" PRIMARY KEY ("Id")
);

CREATE OR REPLACE TRIGGER trg_application_menu_latest_update BEFORE UPDATE ON "application_menu" FOR EACH ROW EXECUTE FUNCTION update_latestupdate_column();

CREATE TABLE IF NOT EXISTS application_menu_item (
	"Id" integer GENERATED BY DEFAULT AS IDENTITY,
	"MenuId" integer NOT NULL,
	"Title" text NOT NULL,
	"Description" text NULL,
	"Icon" text NULL,
	"ParentId" integer NULL,
	"DividerBefore" boolean NULL,
	"DividerAfter" boolean NULL,
	"StatusId" smallint NULL,
	"OrderBy" smallint NULL,
	"Path" text NULL,
	"ApplicationPageId" integer NULL,
	"LatestUpdate" timestamp with time zone NOT NULL DEFAULT now(),
	CONSTRAINT "PK_application_menu_item" PRIMARY KEY ("Id")
);

CREATE OR REPLACE TRIGGER trg_application_menu_item_latest_update BEFORE UPDATE ON "application_menu_item" FOR EACH ROW EXECUTE FUNCTION update_latestupdate_column();

CREATE TABLE IF NOT EXISTS application_page (
	"Id" integer GENERATED BY DEFAULT AS IDENTITY,
	"Path" text NOT NULL,
	"ClientApplicationId" smallint NOT NULL,
	"CodeClassName" text NOT NULL,
	"CodeSyncState" smallint NOT NULL,
	"Title" text NULL,
	"Description" text NULL,
	"KbItemKey" text NULL,
	"IsNotForMenu" boolean NULL,
	"LatestUpdate" timestamp with time zone NOT NULL DEFAULT now(),
	CONSTRAINT "PK_application_page" PRIMARY KEY ("Id")
);

CREATE OR REPLACE TRIGGER trg_application_page_latest_update BEFORE UPDATE ON "application_page" FOR EACH ROW EXECUTE FUNCTION update_latestupdate_column();

-- Id and CompanyId come from migration 20261123140437 (the first version had the key (PermissionRoleId, ApplicationMenuItemId)).
-- CompanyId NULL = the default rows of a system role; a company id = that company's own rows for the role.
CREATE TABLE IF NOT EXISTS role2menu_item (
	"Id" integer GENERATED BY DEFAULT AS IDENTITY,
	"PermissionRoleId" integer NOT NULL,
	"ApplicationMenuItemId" integer NOT NULL,
	"CompanyId" integer NULL,
	"CanView" boolean NULL,
	"CanEdit" boolean NULL,
	"CanDelete" boolean NULL,
	"CanCreate" boolean NULL,
	"LatestUpdate" timestamp with time zone NOT NULL DEFAULT now(),
	CONSTRAINT "PK_role2menu_item" PRIMARY KEY ("Id")
);
CREATE UNIQUE INDEX IF NOT EXISTS "UX_role2menu_item_default" ON role2menu_item ("PermissionRoleId", "ApplicationMenuItemId") WHERE "CompanyId" IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS "UX_role2menu_item_company" ON role2menu_item ("PermissionRoleId", "ApplicationMenuItemId", "CompanyId") WHERE "CompanyId" IS NOT NULL;

CREATE OR REPLACE TRIGGER trg_role2menu_item_latest_update BEFORE UPDATE ON "role2menu_item" FOR EACH ROW EXECUTE FUNCTION update_latestupdate_column();
